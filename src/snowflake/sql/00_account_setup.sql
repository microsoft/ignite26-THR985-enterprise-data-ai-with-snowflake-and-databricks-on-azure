-- Step 00 · Account setup: warehouse, notify-only resource monitor, Cortex cross-region inference, roles, and one
-- database per data product (CORE, COMMERCIAL, LOYALTY) plus GOVERNANCE. Run as ACCOUNTADMIN. Idempotent.
USE ROLE ACCOUNTADMIN;

CREATE WAREHOUSE IF NOT EXISTS {{WAREHOUSE}}
  WAREHOUSE_SIZE = XSMALL AUTO_SUSPEND = 60 AUTO_RESUME = TRUE INITIALLY_SUSPENDED = TRUE
  STATEMENT_TIMEOUT_IN_SECONDS = 900
  COMMENT = 'THR985 PoC - loading, admin and the users'' default warehouse';
-- One warehouse per consumer, so each one's credits show up separately (spike S4, S5 and war story C).
CREATE WAREHOUSE IF NOT EXISTS WH_CONTOSO_AGENTS
  WAREHOUSE_SIZE = XSMALL AUTO_SUSPEND = 60 AUTO_RESUME = TRUE INITIALLY_SUSPENDED = TRUE
  STATEMENT_TIMEOUT_IN_SECONDS = 120
  COMMENT = 'Design B - SQL generated inside the Cortex Agents';
CREATE WAREHOUSE IF NOT EXISTS WH_CONTOSO_MCP_SQL
  WAREHOUSE_SIZE = XSMALL AUTO_SUSPEND = 60 AUTO_RESUME = TRUE INITIALLY_SUSPENDED = TRUE
  STATEMENT_TIMEOUT_IN_SECONDS = 120
  COMMENT = 'Design A - read-only SQL tool on the MCP server';
CREATE WAREHOUSE IF NOT EXISTS WH_CONTOSO_FED
  WAREHOUSE_SIZE = XSMALL AUTO_SUSPEND = 60 AUTO_RESUME = TRUE INITIALLY_SUSPENDED = TRUE
  STATEMENT_TIMEOUT_IN_SECONDS = 300
  COMMENT = 'Databricks connection - should stay near zero with catalog federation; credits here = double pay';

-- Alerts only: NOTIFY at 50/80/100%, nothing is suspended (account admins with a verified email get the alerts).
CREATE OR REPLACE RESOURCE MONITOR RM_CONTOSO_MONTHLY WITH
  CREDIT_QUOTA = {{MONTHLY_CREDITS}} FREQUENCY = MONTHLY START_TIMESTAMP = IMMEDIATELY
  TRIGGERS ON 50 PERCENT DO NOTIFY ON 80 PERCENT DO NOTIFY ON 100 PERCENT DO NOTIFY;
ALTER WAREHOUSE {{WAREHOUSE}}       SET RESOURCE_MONITOR = RM_CONTOSO_MONTHLY;
ALTER WAREHOUSE WH_CONTOSO_AGENTS  SET RESOURCE_MONITOR = RM_CONTOSO_MONTHLY;
ALTER WAREHOUSE WH_CONTOSO_MCP_SQL SET RESOURCE_MONITOR = RM_CONTOSO_MONTHLY;
ALTER WAREHOUSE WH_CONTOSO_FED     SET RESOURCE_MONITOR = RM_CONTOSO_MONTHLY;

-- Cortex Agents run their models through cross-region inference; AZURE_US keeps processing in Azure US regions.
ALTER ACCOUNT SET CORTEX_ENABLED_CROSS_REGION = '{{CORTEX_CROSS_REGION}}';

-- Roles ------------------------------------------------------------------------------------------------------------
-- Owners: one writer role per data product. Readers and analysts never write.
CREATE ROLE IF NOT EXISTS CONTOSO_ADMIN      COMMENT = 'PoC administrator';
CREATE ROLE IF NOT EXISTS GOVERNANCE_ADMIN   COMMENT = 'Owns and applies row access and masking policies';
CREATE ROLE IF NOT EXISTS CORE_OWNER         COMMENT = 'Writer of the core data product';
CREATE ROLE IF NOT EXISTS COMMERCIAL_OWNER   COMMENT = 'Writer of the commercial data product';
CREATE ROLE IF NOT EXISTS LOYALTY_OWNER      COMMENT = 'Writer of the loyalty data product';
CREATE ROLE IF NOT EXISTS DATA_READER        COMMENT = 'Reads gold core + commercial (row access applies)';
CREATE ROLE IF NOT EXISTS LOYALTY_READER     COMMENT = 'Reads gold loyalty with PII masked';
CREATE ROLE IF NOT EXISTS LOYALTY_STEWARD    COMMENT = 'Reads gold loyalty with PII unmasked';
CREATE ROLE IF NOT EXISTS ANALYST_WEST       COMMENT = 'Ava - West region';
CREATE ROLE IF NOT EXISTS ANALYST_EAST       COMMENT = 'Ben - East region';
CREATE ROLE IF NOT EXISTS ANALYST_HQ         COMMENT = 'Cara - HQ commercial analyst, all regions';
CREATE ROLE IF NOT EXISTS FED_READER         COMMENT = 'Databricks federation connection: gold core + commercial only (war story B)';

GRANT ROLE CORE_OWNER, COMMERCIAL_OWNER, LOYALTY_OWNER, GOVERNANCE_ADMIN TO ROLE CONTOSO_ADMIN;
GRANT ROLE CONTOSO_ADMIN TO ROLE SYSADMIN;
GRANT ROLE CONTOSO_ADMIN TO USER {{ADMIN_USER}};
-- The runner switches to each owner role with USE ROLE, so grant them to the admin user directly as well.
GRANT ROLE CORE_OWNER       TO USER {{ADMIN_USER}};
GRANT ROLE COMMERCIAL_OWNER TO USER {{ADMIN_USER}};
GRANT ROLE LOYALTY_OWNER    TO USER {{ADMIN_USER}};
GRANT ROLE GOVERNANCE_ADMIN TO USER {{ADMIN_USER}};
GRANT ROLE DATA_READER, LOYALTY_READER TO ROLE ANALYST_WEST;
GRANT ROLE DATA_READER, LOYALTY_READER TO ROLE ANALYST_EAST;
GRANT ROLE DATA_READER, LOYALTY_READER TO ROLE ANALYST_HQ;
GRANT ROLE LOYALTY_READER TO ROLE LOYALTY_STEWARD;
-- So the admin (and check_answers.py) can impersonate each persona with USE ROLE.
GRANT ROLE ANALYST_WEST, ANALYST_EAST, ANALYST_HQ, LOYALTY_STEWARD, FED_READER TO ROLE CONTOSO_ADMIN;

GRANT USAGE ON WAREHOUSE {{WAREHOUSE}} TO ROLE CORE_OWNER;
GRANT USAGE ON WAREHOUSE {{WAREHOUSE}} TO ROLE COMMERCIAL_OWNER;
GRANT USAGE ON WAREHOUSE {{WAREHOUSE}} TO ROLE LOYALTY_OWNER;
GRANT USAGE ON WAREHOUSE {{WAREHOUSE}} TO ROLE GOVERNANCE_ADMIN;
GRANT USAGE ON WAREHOUSE {{WAREHOUSE}} TO ROLE DATA_READER;
GRANT USAGE ON WAREHOUSE {{WAREHOUSE}} TO ROLE LOYALTY_READER;
GRANT USAGE ON WAREHOUSE WH_CONTOSO_AGENTS  TO ROLE DATA_READER;
GRANT USAGE ON WAREHOUSE WH_CONTOSO_AGENTS  TO ROLE LOYALTY_READER;
GRANT USAGE ON WAREHOUSE WH_CONTOSO_MCP_SQL TO ROLE DATA_READER;
GRANT USAGE ON WAREHOUSE WH_CONTOSO_FED     TO ROLE FED_READER;

-- Policies are created and applied by a dedicated role (separation of duties).
GRANT APPLY ROW ACCESS POLICY ON ACCOUNT TO ROLE GOVERNANCE_ADMIN;
GRANT APPLY MASKING POLICY ON ACCOUNT TO ROLE GOVERNANCE_ADMIN;

-- Databases: one per data product, owned by its writer role. Schemas: BRONZE (stage over landing files),
-- SILVER (typed, deduplicated Iceberg tables), GOLD (data-product tables, semantic views, agents, MCP servers).
CREATE DATABASE IF NOT EXISTS CORE       COMMENT = 'Data product: stores, products, suppliers, calendar';
CREATE DATABASE IF NOT EXISTS COMMERCIAL COMMENT = 'Data product: sales, promotions, field notes';
CREATE DATABASE IF NOT EXISTS LOYALTY    COMMENT = 'Data product: members (PII) and weekly activity';
CREATE DATABASE IF NOT EXISTS GOVERNANCE COMMENT = 'Row access and masking policies, region mapping';
GRANT OWNERSHIP ON DATABASE CORE       TO ROLE CORE_OWNER       COPY CURRENT GRANTS;
GRANT OWNERSHIP ON DATABASE COMMERCIAL TO ROLE COMMERCIAL_OWNER COPY CURRENT GRANTS;
GRANT OWNERSHIP ON DATABASE LOYALTY    TO ROLE LOYALTY_OWNER    COPY CURRENT GRANTS;
GRANT OWNERSHIP ON DATABASE GOVERNANCE TO ROLE GOVERNANCE_ADMIN COPY CURRENT GRANTS;

USE ROLE CORE_OWNER;
CREATE SCHEMA IF NOT EXISTS CORE.BRONZE;
CREATE SCHEMA IF NOT EXISTS CORE.SILVER;
CREATE SCHEMA IF NOT EXISTS CORE.GOLD;
USE ROLE COMMERCIAL_OWNER;
CREATE SCHEMA IF NOT EXISTS COMMERCIAL.BRONZE;
CREATE SCHEMA IF NOT EXISTS COMMERCIAL.SILVER;
CREATE SCHEMA IF NOT EXISTS COMMERCIAL.GOLD;
USE ROLE LOYALTY_OWNER;
CREATE SCHEMA IF NOT EXISTS LOYALTY.BRONZE;
CREATE SCHEMA IF NOT EXISTS LOYALTY.SILVER;
CREATE SCHEMA IF NOT EXISTS LOYALTY.GOLD;
USE ROLE GOVERNANCE_ADMIN;
CREATE SCHEMA IF NOT EXISTS GOVERNANCE.POLICIES;
