-- Step 50 · Who can read what, the three demo people, and the Databricks federation service user.
--   Ava  -> ANALYST_WEST · Ben -> ANALYST_EAST · Cara -> ANALYST_HQ (all regions; runs Demo 2 Part A and spike S5)
-- People have no password: they sign in only with Entra ID tokens (External OAuth, step 60), mapped by LOGIN_NAME = UPN.
-- Cortex Agents run with the caller's DEFAULT role and need a DEFAULT_WAREHOUSE, so both are set explicitly.

-- Readers: gold only. Row access (step 40) still filters every query, including the SQL that agents generate.
USE ROLE CORE_OWNER;
GRANT USAGE ON DATABASE CORE TO ROLE DATA_READER;
GRANT USAGE ON DATABASE CORE TO ROLE LOYALTY_READER;
GRANT USAGE ON SCHEMA CORE.GOLD TO ROLE DATA_READER;
GRANT USAGE ON SCHEMA CORE.GOLD TO ROLE LOYALTY_READER;
GRANT SELECT ON ALL ICEBERG TABLES IN SCHEMA CORE.GOLD TO ROLE DATA_READER;
GRANT SELECT ON ALL ICEBERG TABLES IN SCHEMA CORE.GOLD TO ROLE LOYALTY_READER;

USE ROLE COMMERCIAL_OWNER;
GRANT USAGE ON DATABASE COMMERCIAL TO ROLE DATA_READER;
GRANT USAGE ON SCHEMA COMMERCIAL.GOLD TO ROLE DATA_READER;
GRANT SELECT ON ALL ICEBERG TABLES IN SCHEMA COMMERCIAL.GOLD TO ROLE DATA_READER;

USE ROLE LOYALTY_OWNER;
GRANT USAGE ON DATABASE LOYALTY TO ROLE LOYALTY_READER;
GRANT USAGE ON SCHEMA LOYALTY.GOLD TO ROLE LOYALTY_READER;
GRANT SELECT ON ALL ICEBERG TABLES IN SCHEMA LOYALTY.GOLD TO ROLE LOYALTY_READER;

-- Federation (war story B): one least-privileged role behind the Databricks connection - only the gold tables
-- Databricks needs. No field notes, no loyalty, no silver.
USE ROLE CORE_OWNER;
GRANT USAGE ON DATABASE CORE TO ROLE FED_READER;
GRANT USAGE ON SCHEMA CORE.GOLD TO ROLE FED_READER;
GRANT SELECT ON ALL ICEBERG TABLES IN SCHEMA CORE.GOLD TO ROLE FED_READER;
USE ROLE COMMERCIAL_OWNER;
GRANT USAGE ON DATABASE COMMERCIAL TO ROLE FED_READER;
GRANT USAGE ON SCHEMA COMMERCIAL.GOLD TO ROLE FED_READER;
GRANT SELECT ON ICEBERG TABLE COMMERCIAL.GOLD.FACT_SALES_DAILY TO ROLE FED_READER;
GRANT SELECT ON ICEBERG TABLE COMMERCIAL.GOLD.DIM_PROMOTION TO ROLE FED_READER;
GRANT SELECT ON ICEBERG TABLE COMMERCIAL.GOLD.BRIDGE_PROMOTION_SKU TO ROLE FED_READER;

-- Cortex: agents for readers (design B), Cortex Analyst for design A.
USE ROLE ACCOUNTADMIN;
GRANT DATABASE ROLE SNOWFLAKE.CORTEX_AGENT_USER TO ROLE DATA_READER;
GRANT DATABASE ROLE SNOWFLAKE.CORTEX_AGENT_USER TO ROLE LOYALTY_READER;
GRANT DATABASE ROLE SNOWFLAKE.CORTEX_USER TO ROLE DATA_READER;
GRANT DATABASE ROLE SNOWFLAKE.CORTEX_USER TO ROLE LOYALTY_READER;
GRANT DATABASE ROLE SNOWFLAKE.CORTEX_USER TO ROLE COMMERCIAL_OWNER;
GRANT DATABASE ROLE SNOWFLAKE.CORTEX_USER TO ROLE LOYALTY_OWNER;

-- People ----------------------------------------------------------------------------------------------------------------
CREATE USER IF NOT EXISTS AVA TYPE = PERSON LOGIN_NAME = '{{UPN_AVA}}';
ALTER USER AVA SET LOGIN_NAME = '{{UPN_AVA}}' DISPLAY_NAME = 'Ava (West region manager)'
  DEFAULT_ROLE = ANALYST_WEST DEFAULT_WAREHOUSE = {{WAREHOUSE}}
  COMMENT = 'Entra ID only (External OAuth) - no password';
GRANT ROLE ANALYST_WEST TO USER AVA;

CREATE USER IF NOT EXISTS BEN TYPE = PERSON LOGIN_NAME = '{{UPN_BEN}}';
ALTER USER BEN SET LOGIN_NAME = '{{UPN_BEN}}' DISPLAY_NAME = 'Ben (East region analyst)'
  DEFAULT_ROLE = ANALYST_EAST DEFAULT_WAREHOUSE = {{WAREHOUSE}}
  COMMENT = 'Entra ID only (External OAuth) - no password';
GRANT ROLE ANALYST_EAST TO USER BEN;

CREATE USER IF NOT EXISTS CARA TYPE = PERSON LOGIN_NAME = '{{UPN_CARA}}';
ALTER USER CARA SET LOGIN_NAME = '{{UPN_CARA}}' DISPLAY_NAME = 'Cara (HQ commercial analyst)'
  DEFAULT_ROLE = ANALYST_HQ DEFAULT_WAREHOUSE = {{WAREHOUSE}}
  COMMENT = 'Entra ID only (External OAuth) - no password';
GRANT ROLE ANALYST_HQ TO USER CARA;

-- Databricks federation service user: key pair only (private key in Key Vault), default warehouse WH_CONTOSO_FED so
-- any query-federation fallback shows up as credits on that warehouse (war story C).
CREATE USER IF NOT EXISTS SVC_DATABRICKS_FED TYPE = SERVICE;
ALTER USER SVC_DATABRICKS_FED SET RSA_PUBLIC_KEY = '{{FED_USER_PUBLIC_KEY}}'
  DEFAULT_ROLE = FED_READER DEFAULT_WAREHOUSE = WH_CONTOSO_FED
  COMMENT = 'Databricks Lakehouse Federation (catalog federation) - key pair, least privilege';
GRANT ROLE FED_READER TO USER SVC_DATABRICKS_FED;

SHOW USERS;
SELECT "name", "login_name", "type", "default_role", "default_warehouse", "has_rsa_public_key"
FROM TABLE(RESULT_SCAN(LAST_QUERY_ID()))
WHERE "name" IN ('AVA', 'BEN', 'CARA', 'SVC_DATABRICKS_FED');
SHOW GRANTS TO ROLE FED_READER;
