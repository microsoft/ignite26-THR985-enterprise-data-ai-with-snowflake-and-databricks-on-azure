#!/usr/bin/env python3
"""Spike S5 - design A (semantic view + read-only SQL) vs design B (Cortex Agent) behind the Snowflake MCP server,
same questions, same model, as Cara (HQ, all regions). Feeds the session's A vs B slide and Demo 2 Part A.

Per run it records: latency, Foundry tokens (in/out/total), MCP calls, MCP payload size, whether the answer holds the
answer-key numbers, and a fingerprint of the SQL that ran (design A: the run-sql argument; design B: SQL found in
the agent's payload). Writes state/bench/s5_<timestamp>.csv and prints medians, accuracy and consistency.

  python foundry/chat.py --as cara --agent contoso-orchestrator-a     # once per design, to give OAuth consent
  python foundry/chat.py --as cara --agent contoso-orchestrator-b
  python foundry/bench.py --runs 20

Snowflake-side cost per design: credits on WH_CONTOSO_MCP_SQL (A) vs WH_CONTOSO_AGENTS (B), plus Cortex AI
credits, from SNOWFLAKE.ACCOUNT_USAGE (lags up to ~3 h) - see README "Spike S5".
"""
import argparse
import csv
import hashlib
import json
import re
import statistics
import time
from collections import Counter
from datetime import datetime

import fdy
from azure.ai.projects import AIProjectClient

pc = fdy.pc
SQL_RE = re.compile(r"(SELECT\b.*?)(?:\"\s*[,}]|\\n\\n|$)", re.I | re.S)
# Models often write non-breaking hyphens (PO‑4471) and narrow spaces; score on plain ASCII.
DASHES = re.compile(r"[\u2010-\u2015\u2212\ufe58\ufe63\uff0d]")


def plain(text: str) -> str:
    return DASHES.sub("-", text).replace("\u00a0", " ").replace("\u202f", " ")


def numbers_in(text: str) -> set[int]:
    return {round(float(n.replace(",", ""))) for n in re.findall(r"\d[\d,]*(?:\.\d+)?", plain(text))}


def questions(key: dict, label: str) -> list[dict]:
    q1 = key["q1_promo_performance_by_region"]
    by_format: Counter = Counter()
    for s in key["q2_west_store_detail"]:
        by_format[s["store_format"]] += int(s["actual_units"])
    return [
        {"id": "q1_by_region", "text": f"Holiday Kickoff units and net sales by region, {label}",
         "expect": [{int(r["actual_units"])} for r in q1] + [{round(r["actual_net_sales"]), int(r["actual_net_sales"])} for r in q1]},
        {"id": "q2_west_by_format", "text": f"Holiday Kickoff units in the West by store format, {label}",
         "expect": [{u} for u in by_format.values()]},
        {"id": "q3_why_west", "text": "Why did the West miss its Holiday Kickoff numbers last week?",
         "expect_any": [r"\bPO\s*-?\s*4471\b", r"\bNorthwind\b(?!\s+Sparkle)"]},
    ]


def sql_text(sql: str) -> str:
    """Comparable SQL: Cortex Analyst appends '-- Generated by Cortex Analyst (request_id: <uuid>)' to every query,
    which would make each run look like a new variant."""
    sql = sql.replace("\\n", "\n").replace('\\"', '"')
    sql = re.sub(r"/\*.*?\*/", " ", re.sub(r"--[^\n]*", " ", sql), flags=re.S)
    return " ".join(sql.lower().split()).rstrip("; ")


def sql_fingerprint(calls: list[dict]) -> str:
    sqls = []
    for c in calls:
        if c["tool"] == "run-sql":
            try:
                args = json.loads(c["arguments"])
                sqls += [v for v in args.values() if isinstance(v, str) and "select" in v.lower()] if isinstance(args, dict) else []
            except json.JSONDecodeError:
                sqls.append(c["arguments"])
        else:
            sqls += [m.group(1) for m in SQL_RE.finditer(c["output"] or "")]
    norm = " | ".join(sql_text(s) for s in sqls)
    return hashlib.sha1(norm.encode()).hexdigest()[:10] if norm else ""


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--runs", type=int, default=20)
    ap.add_argument("--as", dest="persona", default="cara", choices=["ava", "ben", "cara"])
    ap.add_argument("--only", nargs="*", help="question ids, for example q1_by_region")
    args = ap.parse_args()
    key = pc.answer_key()
    qs = [q for q in questions(key, pc.demo_values()["DEMO_WEEK_LABEL"]) if not args.only or q["id"] in args.only]

    out_dir = pc.ROOT / "state" / "bench"
    out_dir.mkdir(parents=True, exist_ok=True)
    out_path = out_dir / f"s5_{datetime.now():%Y%m%d_%H%M%S}.csv"
    rows = []
    cred = fdy.persona_credential(args.persona)
    with AIProjectClient(endpoint=fdy.endpoint(), credential=cred) as project:
        for design in (fdy.DESIGN_A, fdy.DESIGN_B):
            with project.get_openai_client(agent_name=design) as client:
                for q in qs:
                    for n in range(1, args.runs + 1):
                        try:
                            r = fdy.ask(client, q["text"])
                        except Exception as e:  # noqa: BLE001
                            print(f"  {design} {q['id']} #{n}: ERROR {str(e).splitlines()[0][:120]}")
                            rows.append({"design": design, "question": q["id"], "run": n, "error": str(e)[:300]})
                            continue
                        if "expect" in q:
                            found = numbers_in(r["answer"])
                            correct = all(found & alts for alts in q["expect"])
                        else:
                            correct = any(re.search(p, plain(r["answer"]), re.I) for p in q["expect_any"])
                        row = {"design": design, "question": q["id"], "run": n, "latency_s": round(r["latency_s"], 2),
                               "input_tokens": r["input_tokens"], "output_tokens": r["output_tokens"],
                               "total_tokens": r["total_tokens"], "mcp_calls": len(r["calls"]),
                               "mcp_payload_chars": sum(len(c["output"] or "") for c in r["calls"]),
                               "correct": correct, "sql_fingerprint": sql_fingerprint(r["calls"]),
                               "answer": " ".join(r["answer"].split())[:500], "error": ""}
                        rows.append(row)
                        print(f"  {design} {q['id']} #{n}: {row['latency_s']} s, {row['total_tokens']} tokens, "
                              f"{row['mcp_payload_chars']:,} payload chars, {'OK' if correct else 'WRONG'}")
                        time.sleep(1)

    fields = ["design", "question", "run", "latency_s", "input_tokens", "output_tokens", "total_tokens", "mcp_calls",
              "mcp_payload_chars", "correct", "sql_fingerprint", "answer", "error"]
    with out_path.open("w", newline="", encoding="utf-8") as fh:
        w = csv.DictWriter(fh, fieldnames=fields)
        w.writeheader()
        for row in rows:
            w.writerow({k: row.get(k, "") for k in fields})

    pc.banner(f"Summary ({args.runs} runs each, as {args.persona}) - {out_path.name}")
    print(f"  {'design':<24}{'question':<20}{'ok %':>6}{'lat s':>7}{'tokens':>8}{'payload':>9}{'calls':>6}{'SQL variants':>14}")
    for design in (fdy.DESIGN_A, fdy.DESIGN_B):
        for q in qs:
            ok = [r for r in rows if r["design"] == design and r["question"] == q["id"] and not r.get("error")]
            if not ok:
                continue
            med = lambda k: statistics.median(float(r[k] or 0) for r in ok)  # noqa: E731
            variants = len({r["sql_fingerprint"] for r in ok if r["sql_fingerprint"]})
            print(f"  {design:<24}{q['id']:<20}{100 * sum(r['correct'] for r in ok) / len(ok):>6.0f}"
                  f"{med('latency_s'):>7.1f}{med('total_tokens'):>8.0f}{med('mcp_payload_chars'):>9.0f}"
                  f"{med('mcp_calls'):>6.0f}{variants:>14}")


if __name__ == "__main__":
    main()
